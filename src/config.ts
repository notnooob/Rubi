import {existsSync, readFileSync} from "node:fs"
import path from "node:path"
import type {api} from "simplex-chat"
import type {T} from "@simplex-chat/types"
import type {LogLevel} from "./core/logger"

// Load .env from the working directory if present (Node >= 20.12 built-in, no dependency).
try {
  process.loadEnvFile()
} catch {
  /* no .env file — fine */
}

const env = (key: string): string | undefined => {
  const v = process.env[key]?.trim()
  return v === "" ? undefined : v
}
const str = (key: string, def: string): string => env(key) ?? def
const bool = (key: string, def: boolean): boolean => {
  const v = env(key)?.toLowerCase()
  if (v === undefined) return def
  if (["1", "true", "yes", "on"].includes(v)) return true
  if (["0", "false", "no", "off"].includes(v)) return false
  throw new Error(`Invalid boolean for ${key}: "${v}"`)
}
const int = (key: string, def: number): number => {
  const v = env(key)
  if (v === undefined) return def
  const n = Number(v)
  if (!Number.isInteger(n) || n < 0) throw new Error(`Invalid non-negative integer for ${key}: "${v}"`)
  return n
}
const intList = (key: string): number[] =>
  (env(key) ?? "")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => {
      const n = Number(s)
      if (!Number.isInteger(n)) throw new Error(`Invalid id "${s}" in ${key}`)
      return n
    })
const oneOf = <V extends string>(key: string, values: readonly V[], def: V): V => {
  const v = env(key) as V | undefined
  if (v === undefined) return def
  if (!values.includes(v)) throw new Error(`Invalid ${key}: "${v}" (expected one of ${values.join(", ")})`)
  return v
}

function dbConfig(): api.DbConfig {
  const type = oneOf("RUBI_DB_TYPE", ["sqlite", "postgres"] as const, "sqlite")
  if (type === "postgres") {
    const connectionString = env("RUBI_PG_URL")
    if (!connectionString) throw new Error("RUBI_PG_URL is required when RUBI_DB_TYPE=postgres")
    return {type, connectionString, schemaPrefix: env("RUBI_PG_SCHEMA")}
  }
  return {type, filePrefix: str("RUBI_DB_PREFIX", "./storage/rubi"), encryptionKey: env("RUBI_DB_KEY")}
}

/** SimpleX apps keep profile images under this many data-URI characters; bigger profiles may fail to send. */
export const MAX_AVATAR_DATA_URI = 12_500

const DEFAULT_AVATAR = "./assets/avatar.jpg"

/**
 * Profile picture: a .png/.jpg file turned into the data: URI SimpleX profiles expect.
 * Defaults to assets/avatar.jpg (generated by `npm run avatar`); RUBI_AVATAR=none disables it.
 */
function avatar(): string | undefined {
  const configured = env("RUBI_AVATAR")
  if (configured?.toLowerCase() === "none") return undefined
  const file = configured ?? (existsSync(DEFAULT_AVATAR) ? DEFAULT_AVATAR : undefined)
  if (!file) return undefined
  const buf = readFileSync(path.resolve(file))
  // SimpleX apps only strip the exact prefixes "data:image/png;base64," and "data:image/jpg;base64," before
  // decoding. The standard "image/jpeg" makes the picture show up blank, so use "jpg".
  const mime = /\.png$/i.test(file) ? "image/png" : "image/jpg"
  const uri = `data:${mime};base64,${buf.toString("base64")}`
  if (uri.length > MAX_AVATAR_DATA_URI) {
    console.warn(
      `[config] RUBI_AVATAR is ${uri.length} chars as a data URI (limit ~${MAX_AVATAR_DATA_URI}). ` +
        "Use a small JPEG (e.g. `npm run avatar` output) or the profile update may fail."
    )
  }
  return uri
}

export type ReplyMode = "always" | "direct" | "never"

export interface RubiConfig {
  /** Bot profile shown to users. `peerType: bot` and the command menu are added automatically. */
  profile: T.Profile
  /** Auto-reply sent by chat core when someone connects via the bot address (and on group join). */
  welcomeMessage: string
  /** Command prefix. SimpleX clients highlight and menu-complete `/` commands, so keep it `/`. */
  prefix: string
  db: api.DbConfig
  address: {
    /** Create a long-term SimpleX address on first start. */
    create: boolean
    /** Business address: every connecting user gets their own business chat (a special group). */
    business: boolean
  }
  /** Allow users to send files to the bot. */
  allowFiles: boolean
  /** Contact IDs (in this bot's database) that operate the bot. They bypass group permission checks. */
  botAdmins: number[]
  groups: {
    /** Automatically accept group invitations. */
    autoJoin: boolean
    /** Send the welcome message into a group after joining it. */
    greetOnJoin: boolean
  }
  replies: {
    /** Reply to unknown `/commands` in: every chat, DMs only, or never (groups often have several bots). */
    unknownCommand: ReplyMode
    /** In DMs, answer plain (non-command) messages with a hint. */
    nonCommandHintInDirect: boolean
    /** In groups, answer an explicit @mention of me (that isn't a command) with a hint. Replies don't count. */
    mentionHintInGroups: boolean
    /** Show internal error details to bot admins when a command crashes. */
    errorDetailsToBotAdmins: boolean
  }
  limits: {
    /** Default per-user command cooldown in seconds (commands can override). */
    defaultCooldown: number
    /** Anti-flood: at most `floodMax` commands per user in `floodWindowMs`. */
    floodMax: number
    floodWindowMs: number
    /** Default command timeout in seconds (commands can override). 0 = none. */
    defaultTimeout: number
  }
  live: {
    /** Minimum interval between edits of a live message (each edit is a network message to every member). */
    minUpdateIntervalMs: number
    /** Interval of the "working… 3s" elapsed-time ticker on deferred replies. 0 disables the ticker. */
    tickerIntervalMs: number
    /** Stop ticking after this long, to avoid spamming edits during very long jobs. */
    tickerMaxMs: number
  }
  log: {
    level: LogLevel
    network: boolean
    contacts: boolean
  }
  http: {
    /** Route all outgoing HTTP through this proxy: http://host:port or socks5://127.0.0.1:9050 (Tor). */
    proxy?: string
    userAgent: string
  }
    /** Files Rubi downloads to send as attachments (e.g. /reddit media). */
  media: {
    /** Download folder. Files are deleted shortly after SimpleX has uploaded them (30 minutes at the latest). */
    dir: string
    /** Biggest single file Rubi downloads, in bytes. */
    maxFileBytes: number
    /** ffmpeg executable, used to merge Reddit videos with their separate audio track. "" disables it. */
    ffmpeg: string
  }
  /** JSON file for reminders, polls, scheduled jobs. */
  stateFile: string
}

export function loadConfig(): RubiConfig {
  return {
    profile: {
      displayName: str("RUBI_NAME", "Rubi"),
      fullName: "",
      shortDescr: str("RUBI_BIO", "The first multi-purpose SimpleX Chat bot. Send /help."),
      image: avatar(),
    },
    welcomeMessage: "Hi, I'm Rubi. Send /help.",
    prefix: "/",
    db: dbConfig(),
    address: {
      create: bool("RUBI_CREATE_ADDRESS", true),
      business: bool("RUBI_BUSINESS_ADDRESS", false),
    },
    allowFiles: bool("RUBI_ALLOW_FILES", false),
    botAdmins: intList("RUBI_BOT_ADMINS"),
    groups: {
      autoJoin: bool("RUBI_AUTO_JOIN_GROUPS", true),
      greetOnJoin: bool("RUBI_GREET_ON_JOIN", true),
    },
    replies: {
      unknownCommand: oneOf("RUBI_UNKNOWN_COMMAND_REPLY", ["always", "direct", "never"] as const, "direct"),
      nonCommandHintInDirect: bool("RUBI_NON_COMMAND_HINT", true),
      mentionHintInGroups: bool("RUBI_MENTION_HINT", true),
      errorDetailsToBotAdmins: bool("RUBI_ERROR_DETAILS_TO_ADMINS", true),
    },
    limits: {
      defaultCooldown: int("RUBI_DEFAULT_COOLDOWN", 2),
      floodMax: int("RUBI_FLOOD_MAX", 6),
      floodWindowMs: int("RUBI_FLOOD_WINDOW_MS", 15_000),
      defaultTimeout: int("RUBI_DEFAULT_TIMEOUT", 120),
    },
    live: {
      minUpdateIntervalMs: int("RUBI_LIVE_MIN_INTERVAL_MS", 800),
      tickerIntervalMs: int("RUBI_LIVE_TICKER_MS", 3_000),
      tickerMaxMs: int("RUBI_LIVE_TICKER_MAX_MS", 60_000),
    },
    log: {
      level: oneOf("RUBI_LOG_LEVEL", ["debug", "info", "warn", "error"] as const, "info"),
      network: bool("RUBI_LOG_NETWORK", false),
      contacts: true,
    },
    http: {
      proxy: env("RUBI_HTTP_PROXY"),
      userAgent: str("RUBI_HTTP_USER_AGENT", "RubiBot/1.0 (SimpleX chat bot)"),
    },
    media: {
      dir: path.resolve(str("RUBI_MEDIA_DIR", "./storage/media")),
      maxFileBytes: int("RUBI_MEDIA_MAX_MB", 50) * 1024 * 1024,
      ffmpeg: process.env.RUBI_FFMPEG !== undefined && process.env.RUBI_FFMPEG.trim() === "" ? "" : env("RUBI_FFMPEG") ?? "ffmpeg",
    },
    stateFile: str("RUBI_STATE_FILE", "./storage/rubi-state.json"),
  }
}
