/**
 * Writes guide/commands.md, the full command reference, from the same command definitions /help reads
 * (descriptions, details, arguments, examples, permissions). Run `npm run guide` after changing a command;
 * test/guide.test.ts fails while the file is out of date. Custom commands (data/commands/custom/) are left out.
 */
import {writeFileSync} from "node:fs"
import path from "node:path"
import {categoryIcon, CATEGORIES} from "../src/core/categories"
import type {Command} from "../src/core/command"
import {createLogger, setLogLevel} from "../src/core/logger"
import {PERMISSION_LABEL} from "../src/core/permissions"
import {CommandRegistry} from "../src/core/registry"
import {COMMANDS_DIR, ROOT_DIR} from "../src/paths"
import {argUsage, scopeLabel, TYPE_LABEL} from "../data/commands/help"

export const GUIDE_FILE = path.join(ROOT_DIR, "guide", "commands.md")
const CUSTOM_DIR = path.join(COMMANDS_DIR, "custom")

const md = (s: string) => s.replace(/\|/g, "\\|")
const anchor = (name: string) => `cmd-${name}`
const duration = (s: number) => (s >= 60 && s % 60 === 0 ? `${s / 60} min` : `${s} s`)

function section(c: Command, prefix: string, defaultCooldown: number): string {
  const p = prefix
  const usage = `${p}${c.name}${c.args.length ? " " + c.args.map(argUsage).join(" ") : ""}`
  const rows: [string, string][] = [
    ["Usage", `\`${md(usage)}\``],
    ["Where", scopeLabel(c.scope)],
    ["Who", PERMISSION_LABEL[c.permission]],
  ]
  if (c.botRole) rows.push(["Rubi must be", `group ${c.botRole} (or higher)`])
  rows.push(["Cooldown", (c.cooldown ?? defaultCooldown) > 0 ? duration(c.cooldown ?? defaultCooldown) : "none"])
  if (c.aliases.length) rows.push(["Aliases", c.aliases.map((a) => `\`${p}${a}\``).join(", ")])
  if (c.live) rows.push(["Live reply", "yes: a placeholder appears right away and turns into the answer"])

  const args = c.args.map((a) => {
    const type = a.choices ? `one of ${a.choices.map((x) => `\`${x}\``).join(", ")}` : TYPE_LABEL[a.type]
    const range = a.min !== undefined || a.max !== undefined ? `, ${a.min ?? "…"}–${a.max ?? "…"}` : ""
    return `- \`${a.name}\` (${a.required ? "required" : "optional"}, ${type}${range}): ${a.description}`
  })
  return [
    `<a id="${anchor(c.name)}"></a>`,
    `### \`${p}${c.name}\``,
    "",
    c.description,
    ...(c.details && c.details !== c.description ? ["", c.details] : []),
    "",
    "| | |",
    "|---|---|",
    ...rows.map(([k, v]) => `| ${k} | ${v} |`),
    ...(args.length ? ["", "**Arguments**", "", ...args] : []),
    ...(c.examples.length ? ["", "**Examples**", "", ...c.examples.map((e) => `- \`${p}${e.replace(/^\//, "")}\``)] : []),
  ].join("\n")
}

/** The whole reference as Markdown. */
export function renderCommandReference(): string {
  setLogLevel("error")
  const reg = new CommandRegistry(COMMANDS_DIR, createLogger("guide"))
  reg.load()
  const all = reg.all().filter((c) => !c.file.startsWith(CUSTOM_DIR + path.sep))
  const byCat = CommandRegistry.byCategory(all.filter((c) => !c.hidden))
  const hidden = all.filter((c) => c.hidden)
  // documents the defaults, so the file doesn't depend on anyone's .env (RUBI_PREFIX, RUBI_DEFAULT_COOLDOWN)
  const prefix = "/"
  const cooldown = 2

  const toc = [...byCat].map(([cat, cmds]) => `- ${categoryIcon(cat)} **${cat}**: ${cmds.map((c) => `[\`${prefix}${c.name}\`](#${anchor(c.name)})`).join(" ")}`)
  const parts = [
    "# Rubi command reference",
    "",
    "<!-- Generated by `npm run guide` from data/commands. Don't edit by hand: change the command, then regenerate. -->",
    "",
    `Every command, with the same information as \`${prefix}help <command>\` in the chat. New here? Start with the [user guide](using-rubi.md); group admins, see the [admin guide](group-admins.md).`,
    "",
    "**Reading the usage line:** `<name>` is required, `[name]` is optional, `name...` takes the rest of the message, and `a|b` means one of those words. Members can be given as an @mention, a name (`@'Jo Do'` with spaces) or `#id` (see `/members`). Numbers may use commas (`1,000`).",
    "",
    `**Cooldown** is how long one person waits before using the same command again (default ${duration(cooldown)}). Bot admins skip cooldowns.`,
    "",
    ...toc,
  ]
  for (const [cat, cmds] of byCat) {
    const info = CATEGORIES.find((c) => c.name === cat)?.description
    parts.push("", `## ${categoryIcon(cat)} ${cat}`, ...(info ? ["", info + "."] : []))
    for (const c of cmds) parts.push("", section(c, prefix, cooldown))
  }
  if (hidden.length) {
    parts.push("", "## ⚙️ Buttons and helpers", "", "Rubi's buttons send these. You rarely type them yourself, and they're not in `/help`.")
    for (const c of hidden) parts.push("", section(c, prefix, cooldown))
  }
  return parts.join("\n") + "\n"
}

if (require.main === module) {
  writeFileSync(GUIDE_FILE, renderCommandReference())
  console.log(`wrote ${path.relative(process.cwd(), GUIDE_FILE)}`)
}
